# Program wyświetlający dane studenta

name = "Adam"              # Imię studenta
age = 20                   # Wiek studenta
height = 180               # Wzrost studenta w cm

print(f"My name is {name}.")                    # Wyświetlenie imienia
print(f"I am {age} years old, and my height is {height} cm.")  # Wiek i wzrost
print(f"In 6 years I will be {age + 6} years old.")            # Wiek za 6 lat