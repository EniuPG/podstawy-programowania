# Using math module

import math  # import modułu matematycznego

square_root = math.sqrt(7)  # pierwiastek z 7
print("Square root of 7:", square_root)  # wynik

natural_log = math.log(5)  # logarytm naturalny
print("Natural logarithm of 5:", natural_log)  # wynik

sine_value = math.sin(math.radians(90))  # sinus 90 stopni
print("Sine of 90 degrees:", sine_value)  # wynik