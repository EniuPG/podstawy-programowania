# Operacje na napisach

movie = "The Lord of the Rings: The Return of the King"  # Tytuł filmu

print("Number of characters:", len(movie))  # Liczba znaków

print(movie.upper())                        # Wielkie litery

print(movie.lower())                        # Małe litery

print(movie.count("e"))                     # Liczba wystąpień litery e

print(movie.find("Lord"))                   # Pozycja słowa Lord

print(movie.find("dragon"))                 # Pozycja słowa dragon (-1 jeśli nie istnieje)