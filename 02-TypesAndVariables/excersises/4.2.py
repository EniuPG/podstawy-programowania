# Program obliczający dochód rodziny na osobę

father_income = 5450          # Dochód ojca
mother_income = 4920          # Dochód matki
family_members = 5            # Liczba członków rodziny

total_income = father_income + mother_income      # Łączny dochód rodziny

income_per_person = total_income / family_members # Dochód na osobę

print(f"Total family income is {total_income}, and income per person is {income_per_person}.")  # Wyświetlenie wyników