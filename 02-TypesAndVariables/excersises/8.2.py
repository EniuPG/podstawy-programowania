# Calculation of circle area and circumference

r = float(input("Enter radius: "))  # Wczytanie promienia

pi = 3.14                           # Stała PI

area = pi * r ** 2                  # Obliczenie pola koła

circumference = 2 * pi * r          # Obliczenie obwodu koła

print(f"Radius: {r}")               # Wyświetlenie promienia

print(f"Circumference: {circumference}")  # Wyświetlenie obwodu

print(f"Area: {area}")              # Wyświetlenie pola