# Program wyświetlający kody znaków

print(f"a {ord('a')}")    # Kod litery a
print(f"b {ord('b')}")    # Kod litery b
print(f"z {ord('z')}")    # Kod litery z

print(f"A {ord('A')}")    # Kod litery A
print(f"B {ord('B')}")    # Kod litery B
print(f"Z {ord('Z')}")    # Kod litery Z

print(f"1 {ord('1')}")    # Kod cyfry 1

print(f"= {ord('=')}")    # Kod znaku =

