# Program wyświetlający kod każdej litery imienia

name = "Jakub"   # Zamień na swoje imię

print(f"The letter {name[0]} has a code {ord(name[0])}")  # Pierwsza litera

print(f"The letter {name[1]} has a code {ord(name[1])}")  # Druga litera

print(f"The letter {name[2]} has a code {ord(name[2])}")  # Trzecia litera

print(f"The letter {name[3]} has a code {ord(name[3])}")  # Czwarta litera

print(f"The letter {name[4]} has a code {ord(name[4])}")  # Piąta litera