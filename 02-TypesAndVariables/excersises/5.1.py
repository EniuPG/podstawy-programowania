# Program wczytujący imię i nazwisko użytkownika

first_name = input("Enter your first name: ")   # Pobranie imienia
last_name = input("Enter your last name: ")     # Pobranie nazwiska

full_name = first_name + " " + last_name        # Połączenie imienia i nazwiska

print(f"Your first name is {first_name} and your last name is {last_name}")  # Wyświetlenie danych

print(f"And your full name is {full_name}")     # Wyświetlenie pełnego imienia i nazwiska