min_number = min(4, 7, 2, 3, 9, 8)  # najmniejsza liczba
print("Min number of 4,7,2,3,9,8 is", min_number)  # wyświetlenie wyniku

str_length = len("computer science")  # długość napisu
print('The number of characters in "computer science" is', str_length)  # wynik

letter = input("Enter a letter: ")  # odczyt znaku
print("Entered letter:", letter)  # wynik

number = int("20303")  # zamiana tekstu na liczbę
print("Number:", number)  # wynik

binary_number = bin(304)  # zapis binarny
print("Binary:", binary_number)  # wynik

hex_number = hex(304)  # zapis szesnastkowy
print("Hexadecimal:", hex_number)  # wynik

unicode_euro = ord("€")  # kod Unicode znaku €
print("Unicode code of €:", unicode_euro)  # wynik

absolute_value = abs(-17)  # wartość bezwzględna
print("Absolute value:", absolute_value)  # wynik