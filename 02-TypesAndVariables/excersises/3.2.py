# Program obliczający sumę trzech liczb

number1 = 71                # Pierwsza liczba
number2 = 14                # Druga liczba
number3 = 20                # Trzecia liczba

result = number1 + number2 + number3  # Obliczenie sumy

print("Number 1:", number1)           # Wyświetlenie pierwszej liczby
print("Number 2:", number2)           # Wyświetlenie drugiej liczby
print("Number 3:", number3)           # Wyświetlenie trzeciej liczby
print("The result of summation:", result)  # Wyświetlenie wyniku