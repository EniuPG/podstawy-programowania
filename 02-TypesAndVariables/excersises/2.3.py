print(type(50))                   # int - liczba całkowita

print(type(149.17))               # float - liczba zmiennoprzecinkowa

print(type(4 * 7))                # int - wynik 28 jest liczbą całkowitą

print(type(4.0 * 7))              # float - ponieważ jedno z działań używa float

print(type("Krakow University of Economics"))  # str - tekst (łańcuch znaków)

print(type(True))                 # bool - wartość logiczna

print(type(2 > 5))                # bool - wynik porównania to False

# ==========================================
# Odpowiedzi do zadania o typach danych
# ==========================================

# 50 -> int
# 149.17 -> float
# 4 * 7 -> int
# 4.0 * 7 -> float
# "Krakow University of Economics" -> str
# True -> bool
# 2 > 5 -> bool