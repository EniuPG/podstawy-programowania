# Program wyświetlający szczegółowe informacje o pracowniku

employee = "Mr. John May, born on 1998-02-16"  # Dane pracownika

print(f"Name: {employee[4:8]}")        # Imię

print(f"Surname: {employee[9:12]}")    # Nazwisko

print(f"Born: {employee[22:32]}")      # Data urodzenia

print(f"Initials: {employee[4]}{employee[9]}")  # Inicjały