# 1) 3 * 2 + 1
wynik1 = 3 * 2 + 1               # Najpierw mnożenie, potem dodawanie
print(wynik1)                     # Wynik: 7

# Operatory: * , + (2 operatory)
# Argumenty: 3, 2, 1 (3 argumenty)

# 2) 5 + 10 * 5
wynik2 = 5 + 10 * 5              # Najpierw mnożenie, potem dodawanie
print(wynik2)                     # Wynik: 55

# Operatory: + , * (2 operatory)
# Argumenty: 5, 10, 5 (3 argumenty)

# 3) 4 + 4 / 2 ** 2
wynik3 = 4 + 4 / 2 ** 2          # Potęga, potem dzielenie, potem dodawanie
print(wynik3)                     # Wynik: 5.0

# Operatory: + , / , ** (3 operatory)
# Argumenty: 4, 4, 2, 2 (4 argumenty)

# 4) 4 % 3 % 2 % 1
wynik4 = 4 % 3 % 2 % 1           # Kolejne operacje modulo
print(wynik4)                     # Wynik: 0

# Operatory: %, %, % (3 operatory)
# Argumenty: 4, 3, 2, 1 (4 argumenty)

# 5) 1 + 2 % 3 ** 4 * 5
wynik5 = 1 + 2 % 3 ** 4 * 5      # Potęga, modulo, mnożenie, dodawanie
print(wynik5)                     # Wynik: 11

# Operatory: +, %, **, * (4 operatory)
# Argumenty: 1, 2, 3, 4, 5 (5 argumentów)

# 6) True != False
wynik6 = True != False           # Sprawdzenie nierówności
print(wynik6)                     # Wynik: True

# Operator: != (1 operator)
# Argumenty: True, False (2 argumenty)